function Get-UiText {
    param(
        [Parameter(Mandatory)] [AllowEmptyString()] [string] $Korean,
        [Parameter(Mandatory)] [AllowEmptyString()] [string] $English
    )
    if ($script:WoWSToolboxLanguage -eq 'en') { return $English }
    return (Convert-ToFormalKoreanText $Korean)
}

