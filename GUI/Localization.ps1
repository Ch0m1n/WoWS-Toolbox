function Set-WoWSToolboxLanguage {
    param([AllowEmptyString()] [string] $Language)
    $normalized = ([string] $Language).Trim().ToLowerInvariant()
    $script:WoWSToolboxLanguage = if ($normalized -eq 'ko') { 'ko' } else { 'en' }
}

