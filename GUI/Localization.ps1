function Convert-XamlToUiLanguage {
    param([Parameter(Mandatory)] [string] $Xaml)
    if ($script:WoWSToolboxLanguage -ne 'en') {
        return (Convert-ToFormalKoreanText $Xaml)
    }
    $result = $Xaml
    foreach ($pair in $script:WoWSToolboxEnglishText.GetEnumerator()) {
        $source = '="' + [string] $pair.Key + '"'
        $target = '="' + [string] $pair.Value + '"'
        $result = $result.Replace($source, $target)
    }
    return $result
}

function Get-WoWSToolboxLanguageMarker {
    param([Parameter(Mandatory)] [string] $PackageRoot)
    $markerPath = Join-Path $PackageRoot 'app-language.txt'
    if (-not (Test-Path -LiteralPath $markerPath -PathType Leaf)) { return 'en' }
    try {
        $value = (Get-Content -Raw -LiteralPath $markerPath).Trim().ToLowerInvariant()
        if ($value -in @('ko', 'en')) { return $value }
    }
    catch {}
    return 'en'
}

function Set-WoWSToolboxLanguageMarker {
    param(
        [Parameter(Mandatory)] [string] $PackageRoot,
        [Parameter(Mandatory)] [ValidateSet('ko', 'en')] [string] $Language
    )
    try {
        [IO.File]::WriteAllText(
            (Join-Path $PackageRoot 'app-language.txt'),
            $Language + [Environment]::NewLine,
            [Text.UTF8Encoding]::new($false)
        )
        return $true
    }
    catch { return $false }
}
